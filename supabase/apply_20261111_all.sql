-- New or changed cars must match the catalog.
create or replace function public.check_vehicle_catalog()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  c public.vehicle_catalog;
begin
  if tg_op = 'UPDATE'
     and new.brand is not distinct from old.brand
     and new.make is not distinct from old.make
     and new.model is not distinct from old.model
     and new.model_year is not distinct from old.model_year then
    return new; -- e.g. a mileage or name change on an older car
  end if;
  select * into c from public.vehicle_catalog where brand = new.brand and make = new.make;
  if not found then
    raise exception 'Choose the brand and make from the list (% % isn''t in the catalog).', new.brand, new.make
      using errcode = 'check_violation';
  end if;
  if new.model_year is null or new.model_year not between c.year_from and c.year_to then
    raise exception 'The % % was sold as % to % models. Check the year.', c.brand, c.make, c.year_from, c.year_to
      using errcode = 'check_violation';
  end if;
  if new.model is not null and not (new.model = any (c.trims)) then
    raise exception 'Choose a % model from the list, or Not Sure.', c.make
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists vehicles_check_catalog on public.vehicles;
create trigger vehicles_check_catalog
  before insert or update of brand, make, model, model_year on public.vehicles
  for each row execute function public.check_vehicle_catalog();

commit;


