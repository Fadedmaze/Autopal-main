// Builds supabase/migrations/20261111_vehicle_catalog.sql from js/vehicleCatalogData.js,
// so the database and the app offer exactly the same brands, makes, models and years.
// Run after editing the catalog:  node scripts/build-vehicle-catalog-sql.mjs
import { writeFileSync } from "node:fs";
import { CATALOG, LATEST_YEAR } from "../js/vehicleCatalog.js";

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const arr = (list) => `array[${list.map(q).join(", ")}]::text[]`;
const rows = Object.entries(CATALOG).flatMap(([brand, makes]) =>
  makes.map((m) => `  (${q(brand)}, ${q(m.name)}, ${q(m.body)}, ${m.from}, ${m.to}, ${arr(m.trims)})`));

const sql = `-- Vehicle catalog: the only brands, makes, models (trims) and model years a car can be
-- saved with. Generated by scripts/build-vehicle-catalog-sql.mjs from js/vehicleCatalogData.js
-- (${rows.length} makes). Safe to re-run: it refreshes the list.
--
-- Naming follows the app: brand = Honda, make = Civic, model = trim (EX). A model can be
-- left empty ("Not Sure"). Cars saved before this keep working; the check only applies
-- when a car is added or its brand, make, model or year is changed.
begin;

create table if not exists public.vehicle_catalog (
  brand      text not null,
  make       text not null,
  body       text not null check (body in ('sedan', 'hatch', 'coupe', 'suv', 'truck', 'van')),
  year_from  integer not null check (year_from between 1900 and 2100),
  year_to    integer not null check (year_to >= year_from),
  trims      text[] not null default '{}',
  primary key (brand, make)
);

alter table public.vehicle_catalog enable row level security;
drop policy if exists "vehicle catalog: read" on public.vehicle_catalog;
create policy "vehicle catalog: read" on public.vehicle_catalog for select to authenticated using (true);
grant select on public.vehicle_catalog to authenticated;

-- Refresh the list from the app's catalog.
delete from public.vehicle_catalog;
insert into public.vehicle_catalog (brand, make, body, year_from, year_to, trims) values
${rows.join(",\n")};

-- New or changed cars must match the catalog.
create or replace function public.check_vehicle_catalog()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  c public.vehicle_catalog;
begin
  if tg_op = 'UPDATE'
     and new.brand is not distinct from old.brand
     and new.make is not distinct from old.make
     and new.model is not distinct from old.model
     and new.model_year is not distinct from old.model_year then
    return new; -- e.g. a mileage or name change on an older car
  end if;
  select * into c from public.vehicle_catalog where brand = new.brand and make = new.make;
  if not found then
    raise exception 'Choose the brand and make from the list (% % isn''t in the catalog).', new.brand, new.make
      using errcode = 'check_violation';
  end if;
  if new.model_year is null or new.model_year not between c.year_from and c.year_to then
    raise exception 'The % % was sold as % to % models. Check the year.', c.brand, c.make, c.year_from, c.year_to
      using errcode = 'check_violation';
  end if;
  if new.model is not null and not (new.model = any (c.trims)) then
    raise exception 'Choose a % model from the list, or Not Sure.', c.make
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists vehicles_check_catalog on public.vehicles;
create trigger vehicles_check_catalog
  before insert or update of brand, make, model, model_year on public.vehicles
  for each row execute function public.check_vehicle_catalog();

commit;

-- Check: number of brands and makes (expect ${Object.keys(CATALOG).length} and ${rows.length}).
select count(distinct brand) as brands, count(*) as makes from public.vehicle_catalog;
`;
writeFileSync(new URL("../supabase/migrations/20261111_vehicle_catalog.sql", import.meta.url), sql);
console.log(`Wrote ${rows.length} makes for ${Object.keys(CATALOG).length} brands (latest model year ${LATEST_YEAR}).`);
